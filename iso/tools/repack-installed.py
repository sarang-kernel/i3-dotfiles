#!/usr/bin/env python3
"""Rebuild an installable .pkg.tar.zst from a package that is ALREADY INSTALLED (AUR packages cannot be rebuilt reliably: upstream
sources vanish, e.g. old google-chrome versions). Reads /var/lib/pacman/local/<pkg>-<ver>/{desc,files,mtree,install} and the files on disk.
usage: repack-installed.py OUTDIR pkgname...   (runs as a normal user; files only need to be readable)"""
import os, subprocess, sys, tarfile, tempfile, glob

LOCAL = "/var/lib/pacman/local"


def parse_sections(path):
    out, cur = {}, None
    for line in open(path, encoding="utf-8", errors="replace").read().split("\n"):
        if line.startswith("%") and line.endswith("%"):
            cur = line.strip("%"); out[cur] = []
        elif line and cur:
            out[cur].append(line)
    return out


def repack(name, outdir):
    cands = [d for d in glob.glob(f"{LOCAL}/{name}-*") if os.path.isfile(d + "/desc")]
    d = None
    for c in cands:  # name-<ver>-<rel>: the directory whose %NAME% is exactly this package
        if parse_sections(c + "/desc").get("NAME") == [name]:
            d = c; break
    if not d:
        raise SystemExit(f"{name}: not installed")
    desc, files = parse_sections(d + "/desc"), parse_sections(d + "/files")
    one = lambda k, default="": (desc.get(k) or [default])[0]
    ver, arch = one("VERSION"), one("ARCH", "x86_64")
    tmp = tempfile.mkdtemp(prefix="repack.")
    info = ["# Generated by repack-installed.py from the installed package (not rebuilt)",
            f"pkgname = {name}", f"pkgbase = {one('BASE', name)}", f"pkgver = {ver}", f"pkgdesc = {one('DESC')}",
            f"url = {one('URL')}", f"builddate = {one('BUILDDATE', '0')}", f"packager = {one('PACKAGER', 'Unknown Packager')}",
            f"size = {one('SIZE', '0')}", f"arch = {arch}"]
    for k, key in (("LICENSE", "license"), ("REPLACES", "replaces"), ("CONFLICTS", "conflict"), ("PROVIDES", "provides"),
                   ("DEPENDS", "depend"), ("OPTDEPENDS", "optdepend")):
        info += [f"{key} = {v}" for v in desc.get(k, [])]
    info += [f"backup = {b.split()[0]}" for b in files.get("BACKUP", [])]
    info += ["xdata = pkgtype=pkg"]
    open(f"{tmp}/.PKGINFO", "w").write("\n".join(info) + "\n")
    meta = [".PKGINFO"]
    for src, dst in ((d + "/mtree", ".MTREE"), (d + "/install", ".INSTALL")):
        if os.path.isfile(src):
            open(f"{tmp}/{dst}", "wb").write(open(src, "rb").read()); meta.append(dst)
    paths, missing = [], []
    for f in files.get("FILES", []):
        p = "/" + f.rstrip("/")
        (paths if os.path.lexists(p) else missing).append(f.rstrip("/"))
    if missing:
        print(f"{name}: {len(missing)} listed file(s) no longer on disk, skipped (e.g. {missing[0]})", file=sys.stderr)
    os.makedirs(outdir, exist_ok=True)
    out = f"{outdir}/{name}-{ver}-{arch}.pkg.tar.zst"
    zp = subprocess.Popen(["zstd", "-T0", "-3", "-q", "-f", "-o", out], stdin=subprocess.PIPE)
    tf = tarfile.open(fileobj=zp.stdin, mode="w|", format=tarfile.PAX_FORMAT)

    def add(disk, arc):  # root-owned entries; regular file content is streamed (no argument-length limit, no shell)
        ti = tf.gettarinfo(disk, arc)
        ti.uid = ti.gid = 0; ti.uname = ti.gname = "root"
        if ti.isreg():
            with open(disk, "rb") as fh:
                tf.addfile(ti, fh)
        elif ti.isdir() or ti.issym() or ti.islnk():
            tf.addfile(ti)

    for m in meta:                # metadata first, as makepkg does
        add(f"{tmp}/{m}", m)
    for f in paths:
        add("/" + f, f + ("/" if os.path.isdir("/" + f) and not os.path.islink("/" + f) else ""))
    tf.close(); zp.stdin.close()
    if zp.wait():
        raise SystemExit(f"{name}: packing failed")
    print(f"{out}  {os.path.getsize(out) >> 20} MiB  ({len(paths)} entries)")


if __name__ == "__main__":
    for n in sys.argv[2:]:
        repack(n, sys.argv[1])
