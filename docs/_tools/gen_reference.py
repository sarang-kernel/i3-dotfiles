def purpose(path, table_):
    for pre, d, link in sorted(table_, key=lambda t: -len(t[0])):
        if path == pre or (pre.endswith("/") and path.startswith(pre)):
            return d, link
    return "(no description yet)", ""


def first_line(path):
    p = Path(path)
    if not p.is_file():
        return ""
    if p.suffix in (".py", ".sh", "") :
        try:
            hdr = py_docstring_or_header(str(p)) if p.suffix == ".py" else header_block(str(p))
        except Exception:
            hdr = []
        for l in hdr:
            l2 = re.sub(r"^(rog-tune|rog-iso[^:]*):\s*", "", l.strip())
            if l2 and not l2.startswith(("usage", "shellcheck")):
                return l2[:150]
    if p.suffix in (".conf", ".rules", ".service", ".mount", ".automount", ".rasi", ".css", ".toml", ".ini", ".lua", ".desktop", ".timer", ".hook", ".cfg", ".env", ".rc", ".ron", ".xml", ".txt", ".md", ".json", ".frag", ".vert", ".sh", ".py", "") and p.stat().st_size < 60000:
        try:
            lines = p.read_text(errors="replace").splitlines()[:12]
        except Exception:
            return ""
        for l in lines:
            t = l.strip()
            if t.startswith(("#!", "<?xml")):
                continue
            if t.startswith(("#", "//", "--", ";", "/*")):
                c = re.sub(r"^(#+|//+|--+|;+|/\*+)\s*", "", t).rstrip("*/ ").strip()
                c = re.sub(r"^Generated by ~/rog-tune/rog-tune.sh:?\s*", "", c)
                if len(c) > 12 and not c.startswith(("shellcheck", "vim:", "-*-")):
                    return c[:150]
    return ""


def listing(root, tbl, skip=()):
    rows = []
    for f in sorted(root.rglob("*")):
        if not f.is_file() or ".git/" in str(f) or f.suffix in (".png", ".gif", ".pyc"):
            continue
        rel = str(f.relative_to(root))
        if any(rel.startswith(s) for s in skip):
            continue
        d, link = purpose(rel, tbl)
        fl = first_line(f)
        rows.append((rel, (fl or d), d if fl else "", link))
    return rows


def hp_listing():
    rows = []
    for sub in ("conf", "scripts", "system", "theme", "shell", "shaders"):
        for f in sorted((HYPR / sub).rglob("*")):
            if f.is_file() and f.suffix not in (".pyc",) and "__pycache__" not in str(f):
                rows.append((f"~/.config/hypr/{f.relative_to(HYPR)}", first_line(f) or "(see the section for this folder)"))
    for n in ("hyprland.lua", "hypridle.conf", "hyprlock.conf", "hyprlock-colors.conf", "hyprsunset.conf", "server.conf", "webapps.conf", "README.md", "doctor.sh", "install.sh", "report.sh", "packages.txt"):
        if (HYPR / n).exists():
            rows.append((f"~/.config/hypr/{n}", first_line(HYPR / n) or "see the Hyprland setup page"))
    for f in sorted(DASH.rglob("*")):
        if f.is_file() and "vendor" not in str(f) and "__pycache__" not in str(f) and f.suffix != ".pyc":
            rows.append((f"~/.local/share/hp-dash/{f.relative_to(DASH)}", first_line(f) or "see the hp-dash page"))
    rows.append(("~/.local/share/hp-dash/static/vendor/*", "xterm.js, noVNC and the JetBrains Mono Nerd Font (third-party, vendored)"))
    return rows


